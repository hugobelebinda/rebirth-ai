"""Per-language serving routes (Phase 16): ``configs/routing.yaml``.

Generated by ``rebirth package`` / ``rebirth serve rollback`` from the model registry: one
entry per language that has a packaged champion that passed its serving gate. Do not edit by hand.

    languages:
      go:
        model: rebirth-go:7b          # Ollama serving alias → the champion's versioned tag
        tag: rebirth-go:7b-v1
        version: "1"                  # registry version (rebirth-go)
        ...

``--backend auto`` (the default) serves a routed language with its packaged adapter and
falls back to plain Ollama (``OLLAMA_MODEL``, 14B) for everything else.
"""

from __future__ import annotations

import datetime as _dt
import os
import sys
from pathlib import Path

import yaml

from rebirth_ai.lora import ROOT, normalize_lang

ROUTING_FILE = ROOT / "configs" / "routing.yaml"
AUTO_BACKENDS = {"auto", "routed", "rebirth"}


def routing_path() -> Path:
    return Path(os.environ.get("REBIRTH_ROUTING", ROUTING_FILE))


def load_routing(path: Path | None = None) -> dict:
    p = path or routing_path()
    if not p.is_file():
        return {"languages": {}}
    data = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
    data.setdefault("languages", {})
    return data


def save_routing(data: dict, path: Path | None = None) -> Path:
    p = path or routing_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    data = dict(data)
    data["generated_at"] = _dt.datetime.now(_dt.UTC).isoformat(timespec="seconds")
    header = (
        "# Generated by `rebirth package` / `rebirth serve rollback` from the model registry.\n"
        "# Do not edit by hand. Docs: src/rebirth_ai/routing.py\n"
    )
    p.write_text(header + yaml.safe_dump(data, sort_keys=False), encoding="utf-8")
    return p


def route(language: str | None, path: Path | None = None) -> dict | None:
    lang = normalize_lang(language)
    if lang is None:
        return None
    return (load_routing(path).get("languages") or {}).get(lang)


def set_route(lang: str, entry: dict, path: Path | None = None) -> Path:
    data = load_routing(path)
    data["languages"][normalize_lang(lang)] = entry
    return save_routing(data, path)


def translation_route(path: Path | None = None) -> dict | None:
    """The cross-language model ``rebirth migrate --to`` serves (``translation:`` in routing.yaml)."""
    return load_routing(path).get("translation")


def set_translation_route(entry: dict, path: Path | None = None) -> Path:
    data = load_routing(path)
    data["translation"] = entry
    return save_routing(data, path)


def routed_generator(language: str | None, *, path: Path | None = None):
    """``OllamaAdapterClient`` for a routed language, or ``None`` (caller falls back)."""
    entry = route(language, path)
    if not entry:
        return None
    from rebirth_ai.generate.ollama_adapter_client import OllamaAdapterClient

    print(f"[route] {normalize_lang(language)} → {entry['model']} (v{entry.get('version')})", file=sys.stderr)
    return OllamaAdapterClient(model=entry["model"], language=normalize_lang(language))
