#!/usr/bin/env python3
"""Regenerate the lock files from the local training venv (Phase 14).

  requirements-lock.txt   exact `pip freeze` of .venv (local ROCm machine; minus the editable repo)
  requirements-cuda.txt   the same pins for an NVIDIA/CUDA box (AWS g6e): torch from the cu128
                          index, ROCm-only wheels dropped, triton left to torch's own pin

  .venv/bin/python scripts/cloud/make_requirements.py
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CUDA_INDEX = "https://download.pytorch.org/whl/cu128"
DROP_CUDA = re.compile(r"^(pytorch-triton-rocm|triton|torchaudio|torchvision|amdsmi)==", re.I)


def main() -> int:
    freeze = subprocess.run(
        [sys.executable, "-m", "pip", "freeze", "--exclude-editable"],
        capture_output=True, text=True, check=True,
    ).stdout.splitlines()
    freeze = [ln for ln in freeze if ln and not ln.startswith(("-e ", "#"))]
    header = "# Generated by scripts/cloud/make_requirements.py — do not edit by hand.\n"
    (ROOT / "requirements-lock.txt").write_text(
        header + "# Local training venv (ROCm 6.4, torch 2.9.1+rocm6.4).\n" + "\n".join(freeze) + "\n"
    )
    cuda = []
    for ln in freeze:
        if DROP_CUDA.match(ln):
            continue
        ln = re.sub(r"^torch==([0-9.]+)\+rocm[0-9.]+$", r"torch==\1", ln)
        cuda.append(ln)
    (ROOT / "requirements-cuda.txt").write_text(
        header
        + "# Cloud CUDA venv (AWS Deep Learning Base OSS Nvidia Driver AMI): same pins as the local lock.\n"
        + f"--extra-index-url {CUDA_INDEX}\n"
        + "\n".join(cuda) + "\n"
    )
    print(f"requirements-lock.txt: {len(freeze)} pins · requirements-cuda.txt: {len(cuda)} pins")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
